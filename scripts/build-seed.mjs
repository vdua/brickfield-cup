// Builds seed.sql from data/questions.json.  Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const qs = JSON.parse(readFileSync(join(root, "data/questions.json"), "utf8"));
const esc = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

const kinds = new Set(["practice", "before", "after", "puzzle", "diagnostic", "mock"]);
const rows = qs.map((q, i) => {
  if (!kinds.has(q.k)) throw new Error(`Question ${i}: bad kind ${q.k}`);
  if (q.o && !(Number(q.a) >= 0 && Number(q.a) < q.o.length)) throw new Error(`Question ${i}: bad option index`);
  return `(${q.w | 0}, ${esc(q.k)}, ${esc(q.t)}, ${q.d | 0 || 2}, ${esc(q.q)}, ${esc(q.a)}, ${q.o ? esc(JSON.stringify(q.o)) : "NULL"}, ${esc(q.m)})`;
});

const sql = `-- Generated by scripts/build-seed.mjs — ${qs.length} questions\n` +
  `INSERT INTO questions (week, kind, topic, difficulty, prompt, answer, options, method) VALUES\n` +
  rows.join(",\n") + ";\n";
writeFileSync(join(root, "seed.sql"), sql);
console.log(`seed.sql written with ${qs.length} questions`);
