// Builds seed.sql from data/questions.json.  Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const qs = JSON.parse(readFileSync(join(root, 'data/questions.json'), 'utf8'));
const esc = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const kinds = new Set(['practice', 'before', 'after', 'puzzle', 'diagnostic', 'mock']);
const rows = qs.map((q, i) => {
	if (!kinds.has(q.k)) throw new Error(`Question ${i}: bad kind ${q.k}`);
	if (q.o && !(Number(q.a) >= 0 && Number(q.a) < q.o.length)) throw new Error(`Question ${i}: bad option index`);
	return `(${Math.trunc(q.w) || 0}, ${esc(q.k)}, ${esc(q.t)}, ${Math.trunc(q.d) || 2}, ${esc(q.q)}, ${esc(q.a)}, ${q.o ? esc(JSON.stringify(q.o)) : 'NULL'}, ${esc(q.m)})`;
});

// Idempotent: a row is inserted only if no seed-bank question (not a worksheet one) with the
// same kind, week and prompt exists yet, so re-running init never duplicates the bank.
const cols = 'week, kind, topic, difficulty, prompt, answer, options, method';
const sql = `-- Generated by scripts/build-seed.mjs — ${qs.length} questions (safe to re-run)\n`
  + `WITH seed(${cols}) AS (VALUES\n${rows.join(',\n')})\n`
  + `INSERT INTO questions (${cols})\n`
  + `SELECT ${cols} FROM seed s WHERE NOT EXISTS (\n`
  + `  SELECT 1 FROM questions q WHERE q.kind = s.kind AND q.week = s.week AND q.prompt = s.prompt AND q.worksheet_id IS NULL\n`
  + `);\n`;
writeFileSync(join(root, 'seed.sql'), sql);
console.log(`seed.sql written with ${qs.length} questions`);
